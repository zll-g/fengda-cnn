"""Train the forecast model from memory-mapped snapshot segments exported by the WinForms workbench."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from fengda_cnn.models import CNNLSTMAttentionConfig  # noqa: E402
from fengda_cnn.training.sample_io import NormalizationStats, save_normalization_stats  # noqa: E402
from fengda_cnn.training.snapshot_dataset import (  # noqa: E402
    TARGET_COLUMNS,
    SnapshotSequenceDataset,
    compute_snapshot_normalization,
    load_snapshot_segments,
    model_feature_columns,
    split_snapshot_segments,
    summarize_split,
)
from fengda_cnn.training.trainer import (  # noqa: E402
    TrainConfig,
    TrainingCancelledError,
    torch_available,
    train_forecast_model_with_loaders,
)

try:
    from torch.utils.data import DataLoader
except ImportError:  # pragma: no cover
    DataLoader = None


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", required=True, help="dataset_manifest.json generated by the training workbench.")
    parser.add_argument("--output-dir", required=True, help="Directory for model and training artifacts.")
    parser.add_argument("--train-ratio", type=float, default=0.7)
    parser.add_argument("--val-ratio", type=float, default=0.15)
    parser.add_argument("--test-ratio", type=float, default=0.15)
    parser.add_argument("--epochs", type=int, default=30)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--learning-rate", type=float, default=1e-3)
    parser.add_argument("--weight-decay", type=float, default=1e-4)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--device", default="auto")
    parser.add_argument("--early-stopping-patience", type=int, default=8)
    parser.add_argument("--loss-name", default="huber", choices=["huber", "mse"])
    parser.add_argument("--trend-loss-weight", type=float, default=0.25)
    parser.add_argument("--scheduler-name", default="none", choices=["none", "plateau"])
    parser.add_argument("--scheduler-factor", type=float, default=0.5)
    parser.add_argument("--scheduler-patience", type=int, default=2)
    parser.add_argument("--min-learning-rate", type=float, default=1e-5)
    parser.add_argument("--selection-metric", default="val_loss")
    parser.add_argument("--target-loss-weights", default="")
    parser.add_argument("--conv-channels-1", type=int, default=64)
    parser.add_argument("--conv-channels-2", type=int, default=128)
    parser.add_argument("--kernel-size", type=int, default=3)
    parser.add_argument("--lstm-hidden-size", type=int, default=128)
    parser.add_argument("--dense-hidden-size", type=int, default=256)
    parser.add_argument("--conv-dropout", type=float, default=0.2)
    parser.add_argument("--lstm-dropout", type=float, default=0.2)
    parser.add_argument("--dense-dropout", type=float, default=0.3)
    parser.add_argument("--stop-file", default="", help="A file whose presence requests cooperative cancellation.")
    return parser.parse_args()


def emit(event_type: str, **payload: object) -> None:
    print(json.dumps({"type": event_type, **payload}, ensure_ascii=False), flush=True)


def parse_target_loss_weights(raw_value: str) -> tuple[float, ...] | None:
    if not raw_value.strip():
        return None
    weights = tuple(float(item.strip()) for item in raw_value.split(",") if item.strip())
    if len(weights) != len(TARGET_COLUMNS):
        raise ValueError(f"目标权重数量应为 {len(TARGET_COLUMNS)}。")
    return weights


def write_json(path: Path, value: object) -> None:
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")


def main() -> int:
    args = parse_args()
    output_dir = Path(args.output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    stop_file = Path(args.stop_file).resolve() if args.stop_file else output_dir / "stop.request"
    try:
        emit("stage", stage="读取训练快照", progress=5)
        segments = load_snapshot_segments(args.manifest)
        split = split_snapshot_segments(segments, args.train_ratio, args.val_ratio, args.test_ratio)
        split_summary = summarize_split(split, segments)
        write_json(output_dir / "split_summary.json", split_summary)
        emit("stage", stage="构建训练集索引", progress=18, **split_summary)

        train_dataset = SnapshotSequenceDataset(segments, split.train)
        val_dataset = SnapshotSequenceDataset(segments, split.validation)
        test_dataset = SnapshotSequenceDataset(segments, split.test)
        emit("stage", stage="计算归一化参数", progress=28)
        normalization = compute_snapshot_normalization(train_dataset, should_stop=stop_file.exists)
        save_normalization_stats(
            NormalizationStats(
                feature_mean=normalization.feature_mean,
                feature_std=normalization.feature_std,
                target_mean=normalization.target_mean,
                target_std=normalization.target_std,
            ),
            output_dir,
        )
        train_dataset.normalization = normalization
        val_dataset.normalization = normalization
        test_dataset.normalization = normalization
        feature_columns = model_feature_columns()
        prepared_summary = {
            "x_train_shape": [len(train_dataset), 60, len(feature_columns)],
            "y_train_shape": [len(train_dataset), 60, len(TARGET_COLUMNS)],
            "x_val_shape": [len(val_dataset), 60, len(feature_columns)],
            "y_val_shape": [len(val_dataset), 60, len(TARGET_COLUMNS)],
            "x_test_shape": [len(test_dataset), 60, len(feature_columns)],
            "y_test_shape": [len(test_dataset), 60, len(TARGET_COLUMNS)],
            "feature_columns": feature_columns,
            "target_columns": TARGET_COLUMNS,
            "split_mode": split_summary["split_mode"],
        }
        write_json(output_dir / "prepared_data_summary.json", prepared_summary)
        emit("stage", stage="准备模型训练", progress=35, **prepared_summary)

        if not torch_available() or DataLoader is None:
            raise RuntimeError("未安装 PyTorch，无法执行模型训练。")
        train_loader = DataLoader(train_dataset, batch_size=args.batch_size, shuffle=True)
        val_loader = DataLoader(val_dataset, batch_size=args.batch_size, shuffle=False)
        test_loader = DataLoader(test_dataset, batch_size=args.batch_size, shuffle=False)
        model_config = CNNLSTMAttentionConfig(
            input_size=len(feature_columns),
            output_steps=60,
            output_size=len(TARGET_COLUMNS),
            conv_channels_1=args.conv_channels_1,
            conv_channels_2=args.conv_channels_2,
            kernel_size=args.kernel_size,
            lstm_hidden_size=args.lstm_hidden_size,
            dense_hidden_size=args.dense_hidden_size,
            conv_dropout=args.conv_dropout,
            lstm_dropout=args.lstm_dropout,
            dense_dropout=args.dense_dropout,
        )
        train_config = TrainConfig(
            epochs=args.epochs,
            batch_size=args.batch_size,
            learning_rate=args.learning_rate,
            weight_decay=args.weight_decay,
            seed=args.seed,
            device=args.device,
            early_stopping_patience=args.early_stopping_patience,
            loss_name=args.loss_name,
            trend_loss_weight=args.trend_loss_weight,
            scheduler_name=args.scheduler_name,
            scheduler_factor=args.scheduler_factor,
            scheduler_patience=args.scheduler_patience,
            min_learning_rate=args.min_learning_rate,
            target_loss_weights=parse_target_loss_weights(args.target_loss_weights),
            selection_metric=args.selection_metric,
        )
        write_json(output_dir / "training_config.json", {"model": model_config.__dict__, "train": train_config.__dict__})

        def on_epoch(event: dict[str, object]) -> None:
            current = int(event["epoch"])
            total = max(int(event["total_epochs"]), 1)
            emit("epoch", progress=35 + (current / total * 55), **event)

        summary = train_forecast_model_with_loaders(
            train_loader=train_loader,
            val_loader=val_loader,
            test_loader=test_loader,
            model_config=model_config,
            train_config=train_config,
            target_mean=normalization.target_mean,
            target_std=normalization.target_std,
            target_names=TARGET_COLUMNS,
            output_dir=output_dir,
            input_steps=60,
            progress_callback=on_epoch,
            should_stop=stop_file.exists,
        )
        emit("stage", stage="训练完成，正在校验模型文件", progress=94)
        emit("completed", progress=100, summary=summary)
        return 0
    except (TrainingCancelledError, InterruptedError) as error:
        emit("cancelled", message=str(error))
        return 2
    except Exception as error:  # noqa: BLE001 - surfaced to the WinForms operator
        emit("error", message=str(error))
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
